# Generates src/s3/tz_db.c: every zone in the host's zone.tab (plus UTC)
# with its POSIX TZ rule, which is the footer line of each TZif v2+ file.
# newlib's tzset() only understands POSIX rules, not IANA names.
# Usage: python3 tools/gen_tz_db.py [/usr/share/zoneinfo] > src/s3/tz_db.c
import os
import sys

root = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
version = open(os.path.join(root, "+VERSION")).read().strip() if os.path.exists(os.path.join(root, "+VERSION")) else "?"


def posix_rule(name):
    data = open(os.path.join(root, name), "rb").read()
    if not data.startswith(b"TZif") or data[4:5] < b"2":
        raise ValueError(f"{name}: no v2+ footer")
    return data.rstrip(b"\n").rsplit(b"\n", 1)[1].decode()


names = {"UTC"}
for line in open(os.path.join(root, "zone.tab")):
    if line.strip() and not line.startswith("#"):
        names.add(line.split("\t")[2].strip())

print(f"// Generated by tools/gen_tz_db.py from tzdata {version}; do not edit.")
print('#include "tz.h"\n')
print("const tz_entry_t tz_db[] = {")
for name in sorted(names):
    print(f'    {{"{name}", "{posix_rule(name)}"}},')
print("};\n")
print("const size_t tz_db_count = sizeof(tz_db) / sizeof(tz_db[0]);")
